    [Fact]
    public async Task RefreshTokenAsync_WithValidToken_ShouldRotateTokens()
    {
        var oldRefreshTokenValue = "old_refresh_token";
        var user = new User("user@lms.com", "hashed_password", "John", "Doe", "Student");
        user.ConfirmEmail();

        var oldToken = new RefreshToken(oldRefreshTokenValue, DateTime.UtcNow.AddDays(1), user);

        _refreshTokenRepositoryMock.Setup(r => r.GetByTokenAsync(oldRefreshTokenValue)).ReturnsAsync(oldToken);
        _jwtTokenGeneratorMock.Setup(j => j.GenerateAccessToken(It.IsAny<User>())).Returns("new_access_token");
        _jwtTokenGeneratorMock.Setup(j => j.GenerateRefreshToken()).Returns("new_refresh_token");
        _contextMock.Setup(c => c.SaveChangesAsync(It.IsAny<CancellationToken>())).ReturnsAsync(1);

        var result = await _authService.RefreshTokenAsync(oldRefreshTokenValue);

        result.Should().NotBeNull();
        result!.AccessToken.Should().Be("new_access_token");
        result.RefreshToken.Should().Be("new_refresh_token");
        oldToken.IsRevoked.Should().BeTrue("old token should be revoked");
    }

    [Fact]
    public async Task RefreshTokenAsync_WithExpiredToken_ShouldReturnNull()
    {
        var user = new User("user@lms.com", "hash", "John", "Doe", "Student");
        var expiredToken = new RefreshToken("expired_token", DateTime.UtcNow.AddDays(-1), user);

        _refreshTokenRepositoryMock.Setup(r => r.GetByTokenAsync("expired_token")).ReturnsAsync(expiredToken);

        var result = await _authService.RefreshTokenAsync("expired_token");
        result.Should().BeNull("expired token should be rejected");
    }

