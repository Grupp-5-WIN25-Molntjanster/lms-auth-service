    /// <summary>
    /// TEST: Verify email calls Verification service and confirms email on success.
    /// </summary>
    [Fact]
    public async Task VerifyEmailAsync_WithValidCode_ShouldReturnTrue()
    {
        // ARRANGE
        var user = new User("test@lms.com", "hash", "Test", "User", "Student");

        _userRepositoryMock
            .Setup(r => r.GetByEmailAsync("test@lms.com"))
            .ReturnsAsync(user);

        // Mock Email Service to return valid
        _verificationClientMock
            .Setup(e => e.ValidateCodeAsync("test@lms.com", "245789"))
            .ReturnsAsync(true);

        _contextMock
            .Setup(c => c.SaveChangesAsync(It.IsAny<CancellationToken>()))
