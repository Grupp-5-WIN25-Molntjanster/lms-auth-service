    /// <summary>
    /// TEST: Unverified user should NOT receive tokens on login.
    /// </summary>
    [Fact]
    public async Task LoginAsync_WithUnverifiedEmail_ShouldRequireVerification()
    {
        var request = new LoginRequest
        {
            Email = "unverified@lms.com",
            Password = "correct_password"
        };

        var unverifiedUser = new User(
            "unverified@lms.com",
            "hashed_password",
            "John",
            "Doe",
            "Student");
        // EmailConfirmed is false by default

        _userRepositoryMock
            .Setup(r => r.GetByEmailAsync(request.Email))
            .ReturnsAsync(unverifiedUser);

        _passwordHasherMock
            .Setup(p => p.Verify(request.Password, unverifiedUser.PasswordHash))
            .Returns(true);

        var result = await _authService.LoginAsync(request);

        result.Should().NotBeNull("user exists and password is correct");
        result!.RequiresEmailVerification.Should().BeTrue("email not verified yet");
        result.AccessToken.Should().BeEmpty("no token until verified");
    }

    /// <summary>
    /// TEST: Verified user with valid credentials should receive tokens.
    /// </summary>
    [Fact]
    public async Task LoginAsync_WithVerifiedEmail_ShouldReturnTokens()
    {
        var request = new LoginRequest
        {
            Email = "verified@lms.com",
            Password = "correct_password"
        };

        var verifiedUser = new User(
            "verified@lms.com",
            "hashed_password",
            "John",
            "Doe",
            "Student");
        verifiedUser.ConfirmEmail();

        _userRepositoryMock
            .Setup(r => r.GetByEmailAsync(request.Email))
            .ReturnsAsync(verifiedUser);

        _passwordHasherMock
            .Setup(p => p.Verify(request.Password, verifiedUser.PasswordHash))
            .Returns(true);

        _jwtTokenGeneratorMock
            .Setup(j => j.GenerateAccessToken(It.IsAny<User>()))
            .Returns("login_access_token");
        _jwtTokenGeneratorMock
            .Setup(j => j.GenerateRefreshToken())
            .Returns("login_refresh_token");

        _contextMock
            .Setup(c => c.SaveChangesAsync(It.IsAny<CancellationToken>()))
            .ReturnsAsync(1);

        var result = await _authService.LoginAsync(request);

        result.Should().NotBeNull("verified user should log in successfully");
        result!.AccessToken.Should().Be("login_access_token");
        result.RequiresEmailVerification.Should().BeFalse("email is verified");
        result.User.EmailConfirmed.Should().BeTrue();
    }

    [Fact]
    public async Task LoginAsync_WithWrongPassword_ShouldReturnNull()
    {
        var request = new LoginRequest { Email = "user@lms.com", Password = "wrong_password" };
        var existingUser = new User("user@lms.com", "hashed_password", "John", "Doe", "Student");
        existingUser.ConfirmEmail();

        _userRepositoryMock.Setup(r => r.GetByEmailAsync(request.Email)).ReturnsAsync(existingUser);
        _passwordHasherMock.Setup(p => p.Verify(request.Password, existingUser.PasswordHash)).Returns(false);

        var result = await _authService.LoginAsync(request);
        result.Should().BeNull("wrong password should fail");
    }

    [Fact]
    public async Task LoginAsync_WithInactiveUser_ShouldReturnNull()
    {
        var request = new LoginRequest { Email = "inactive@lms.com", Password = "password" };
