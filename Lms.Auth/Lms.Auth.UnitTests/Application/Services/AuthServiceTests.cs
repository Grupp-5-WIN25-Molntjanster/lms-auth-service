    }

    // ================================================================
    // REGISTRATION TESTS
    // ================================================================

    /// <summary>
    /// TEST: Registration sends ONLY email to Service Bus.
    /// No code is generated by Auth Service.
    /// User must verify email before receiving tokens.
    /// </summary>
    [Fact]
    public async Task RegisterAsync_WithValidData_ShouldTriggerVerification()
    {
        // ARRANGE
        var request = new RegisterRequest
        {
            Email = "newuser@lms.com",
            Password = "StrongPass123!",
            FirstName = "Jane",
            LastName = "Smith"
        };

        _userRepositoryMock
            .Setup(r => r.EmailExistsAsync(request.Email))
            .ReturnsAsync(false);

        _passwordHasherMock
            .Setup(p => p.Hash(request.Password))
            .Returns("hashed_password_xyz");

        _contextMock
            .Setup(c => c.SaveChangesAsync(It.IsAny<CancellationToken>()))
            .ReturnsAsync(1);

        // ACT
        var result = await _authService.RegisterAsync(request);

        // ASSERT
        result.Should().NotBeNull("registration should succeed");
        result!.RequiresEmailVerification.Should().BeTrue("new users must verify email");
        result.AccessToken.Should().BeEmpty("tokens not issued until email verified");
        result.RefreshToken.Should().BeEmpty("tokens not issued until email verified");
        result.User.Email.Should().Be("newuser@lms.com");

        // Verify Service Bus was called with ONLY the email address
        _verificationClientMock.Verify(
            s => s.SendVerificationAsync("newuser@lms.com"),
            Times.Once,
            "verification email request must be published to Service Bus");

        // Verify user was added
        _userRepositoryMock.Verify(
            r => r.Add(It.IsAny<User>()),
            Times.Once,
            "new user should be added");
    }

    /// <summary>
    /// TEST: Duplicate email should return null and NOT publish to Service Bus.
    /// </summary>
    [Fact]
    public async Task RegisterAsync_WithDuplicateEmail_ShouldReturnNull()
    {
        var request = new RegisterRequest
        {
            Email = "existing@lms.com",
            Password = "StrongPass123!",
            FirstName = "Jane",
            LastName = "Smith"
        };

        _userRepositoryMock
            .Setup(r => r.EmailExistsAsync(request.Email))
            .ReturnsAsync(true);

        var result = await _authService.RegisterAsync(request);

        result.Should().BeNull("duplicate email should fail");

        // Service Bus should NOT be called
        _verificationClientMock.Verify(
            s => s.SendVerificationAsync(It.IsAny<string>()),
            Times.Never,
            "no verification email for duplicate registration");
    }

